import type { ReactNode } from "react";

/**
 * Small icon-badge + message for "nothing here yet" states — replaces the
 * plain grey placeholder text that used to be scattered across list pages
 * (RFIs, Variations, Leads, etc.) with something a little more considered,
 * while staying light enough to drop straight inside an existing Card
 * without turning into a box-within-a-box.
 */
export function EmptyState({
  icon,
  title,
  description,
  className = "px-4 py-10",
}: {
  icon?: ReactNode;
  title: string;
  description?: string;
  className?: string;
}) {
  return (
    <div className={`text-center ${className}`}>
      {icon && (
        <div className="mx-auto flex h-10 w-10 items-center justify-center rounded-full bg-surface text-slate-400 dark:text-slate-500">
          {icon}
        </div>
      )}
      <p className={`text-sm font-medium text-slate-600 dark:text-slate-400 ${icon ? "mt-3" : ""}`}>{title}</p>
      {description && <p className="mt-1 text-xs text-slate-400 dark:text-slate-500">{description}</p>}
    </div>
  );
}

